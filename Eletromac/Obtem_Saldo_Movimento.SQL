CREATE OR REPLACE FUNCTION SANKHYA.Obtem_Saldo_Movimento(
   P_CODEMP IN NUMBER,
   P_CODLOCAL In NUMBER,
   P_DATA IN VARCHAR2)
RETURN NUMBER 
IS VLRPROD NUMBER;
BEGIN
  SELECT NVL(SUM(SALDO * Obtem_Custo_semicm2(CODPROD, DATA)), 0) AS SALDO
    INTO VLRPROD
    FROM SALDO_ESTOQUE
  WHERE DATA = (SELECT MAX(M.DATA) 
                  FROM SALDO_ESTOQUE M
                 WHERE M.CODPROD = SALDO_ESTOQUE.CODPROD
                   AND M.CONTROLE = SALDO_ESTOQUE.CONTROLE
                   AND M.CODEMP = SALDO_ESTOQUE.CODEMP
                   AND M.CODLOCAL = SALDO_ESTOQUE.CODLOCAL
                   AND TO_CHAR(M.DATA, 'MON/YYYY') <= P_DATA)
    AND CODEMP = P_CODEMP
    AND CODLOCAL = P_CODLOCAL;
  RETURN (VLRPROD);
END;
