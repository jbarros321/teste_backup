CREATE OR REPLACE TRIGGER SANKHYA.TRG_UPD_TGFCAB_AFTER_CODVEND
AFTER UPDATE  ON SANKHYA.TGFCAB FOR EACH ROW
/*
TRIGGER PERSONALIZADA
AUTOR: LEANDRO MARCOS MOREIRA
OBJETIVO: SINCRONIZAR VENDEDOR DA TGFCAB COM A TGFITE
*/
WHEN (NEW.CODVEND <> OLD.CODVEND)
DECLARE PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN

  IF STP_GET_ATUALIZANDO THEN
    RETURN;
  END IF;

  IF UPDATING('CODVEND') THEN
     UPDATE TGFITE 
        SET CODVEND = :NEW.CODVEND
      WHERE NUNOTA = :NEW.NUNOTA;
  END IF;
  
  COMMIT;
END;
/
