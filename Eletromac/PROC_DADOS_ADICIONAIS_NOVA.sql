 WHERE UP.CODPROD IN (SELECT CODPRODALT FROM TGFPAL)
   AND UP.CODPROD IN (SELECT CODPROD FROM TGFPRO WHERE AD_SOMANCOM = 'N' AND SOLCOMPRA = 'N');

UPDATE ANALISE_COMPRAS_NOVA UP
   SET (SUGESTAO, VLRSUGESTAO) =
(SELECT CASE WHEN ESTATUAL <= SNK_DIVIDIR(ESTMAX,2) THEN ESTMAX - ESTATUAL
             WHEN ESTATUAL > ESTMAX THEN ESTMAX - ESTATUAL
             ELSE 0
         END AS SUGESTAO,
        CASE WHEN ESTATUAL <= SNK_DIVIDIR(ESTMAX,2) THEN ESTMAX - ESTATUAL
             WHEN ESTATUAL > ESTMAX THEN ESTMAX - ESTATUAL
             ELSE 0
         END * ROUND(NVL(CUSREP, 0), 2) AS VLRSUGESTAO
  FROM ANALISE_COMPRAS_NOVA
  WHERE ANALISE_COMPRAS_NOVA.CODPROD = UP.CODPROD 
   AND ANALISE_COMPRAS_NOVA.CONTROLE = UP.CONTROLE
   AND ANALISE_COMPRAS_NOVA.PK_CODEMP = UP.PK_CODEMP);

