UPDATE ANALISE_COMPRAS_NOVA UP
   SET (ESTATUAL, ESTMIN, MEDIAPVEND, SOMPEDPEN, ESTMAX, ESTEXC) =
(SELECT ESTATUAL
      , ESTMIN
      , MEDIAPVEND
      , SOMPEDPEN
      , ESTMAX
      , ESTEXC
FROM
   (SELECT PK_CODEMP
     , CODPROD
     , CONTROLE
     , NVL(SUM(UNIAO.ESTATUAL), 0) AS ESTATUAL
     , NVL(SUM(UNIAO.ESTMIN), 0) AS ESTMIN
     , NVL(SUM(UNIAO.MEDIAPVEND), 0) AS MEDIAPVEND
     , NVL(SUM(UNIAO.SOMPEDPEN), 0) AS SOMPEDPEN
     , NVL(SUM(UNIAO.ESTMAX), 0) AS ESTMAX
     , NVL(SUM(UNIAO.ESTEXC), 0) AS ESTEXC
  FROM
(SELECT COM.PK_CODEMP
     , PAL.CODPROD
     , NVL(COM.CONTROLE, ' ') AS CONTROLE
     , NVL(COM.ESTATUAL, 0) AS ESTATUAL
     , NVL(COM.ESTMIN, 0) AS ESTMIN
     , NVL(COM.MEDIAPVEND, 0) AS MEDIAPVEND
     , NVL(COM.SOMPEDPEN, 0) AS SOMPEDPEN
     , NVL(COM.ESTMAX, 0) AS ESTMAX
     , NVL(COM.ESTEXC, 0) AS ESTEXC
 FROM ANALISE_COMPRAS_NOVA COM
    , TGFPAL PAL
WHERE COM.CODPROD = PAL.CODPRODALT
UNION
SELECT COM.PK_CODEMP
     , PAL.CODPROD
     , NVL(COM.CONTROLE, ' ') AS CONTROLE
     , NVL(COM.ESTATUAL, 0) AS ESTATUAL
     , NVL(COM.ESTMIN, 0) AS ESTMIN
     , NVL(COM.MEDIAPVEND, 0) AS MEDIAPVEND
     , NVL(COM.SOMPEDPEN, 0) AS SOMPEDPEN
     , NVL(COM.ESTMAX, 0) AS ESTMAX
     , NVL(COM.ESTEXC, 0) AS ESTEXC
 FROM ANALISE_COMPRAS_NOVA COM
    , TGFPAL PAL
WHERE COM.CODPROD = PAL.CODPROD) UNIAO
GROUP BY PK_CODEMP, CODPROD, CONTROLE) ANA
WHERE ANA.PK_CODEMP = UP.PK_CODEMP
  AND ANA.CODPROD = UP.CODPROD
  AND ANA.CONTROLE = UP.CONTROLE)
 WHERE UP.CODPROD IN (SELECT CODPROD FROM TGFPAL);

