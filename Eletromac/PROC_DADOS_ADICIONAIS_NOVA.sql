    AND EST.CONTROLE = UP.CONTROLE),0);

UPDATE ANALISE_COMPRAS_NOVA COM
   SET COM.PERIPI =
NVL((SELECT Snk_Dividir(IPI.PERCENTUAL, 100) AS PERIPI
  FROM TGFPRO PRO
     , TGFIPI IPI
 WHERE PRO.CODPROD    =   COM.CODPROD
   AND IPI.CODIPI     =   PRO.CODIPI),0);

 UPDATE ANALISE_COMPRAS_NOVA UP
    SET UP.PEDSOLCOM =
(SELECT NVL(SUM(ITE.QTDNEG), 0) AS QTDNEG
   FROM TGFITE ITE
INNER JOIN TGFCAB CAB ON CAB.NUNOTA = ITE.NUNOTA
WHERE CAB.CODTIPOPER   =   6
  AND ITE.PENDENTE     =   'S'
  AND ITE.CODPROD      =   UP.CODPROD
  AND ITE.CONTROLE     =   UP.CONTROLE);

UPDATE ANALISE_COMPRAS_NOVA UP 
   SET (ESTMIN, ESTMAX) =
(SELECT TRUNC(SNK_DIVIDIR(CASE WHEN MEDIAPVEND = 0 THEN 0 
                   ELSE (MEDIAPVEND / 28) * CASE WHEN PK_CODEMP IN (41,51) THEN 1 
                                                 ELSE 
                   TRUNC(CASE WHEN PRAZOENTR <= 0 THEN 1 
                                                       ELSE PRAZOENTR END)
                                                 END 
                                                       END, QTDEMB) + 0.99) * QTDEMB AS ESTMIN
      , TRUNC(SNK_DIVIDIR(CASE WHEN PK_CODEMP IN (1,31) 
                               THEN NVL(ROUND(AD_MESESTMAX * MEDIAPVEND) + 
                                    ROUND(CASE WHEN MEDIAPVEND = 0 THEN 0 
                                                ELSE (MEDIAPVEND / 28) * TRUNC(CASE WHEN PRAZOENTR <= 0 THEN 1 
                                                                                    ELSE PRAZOENTR END) END),0)
                               ELSE MEDIAPVEND END, QTDEMB) + 0.99) * QTDEMB AS ESTMAX
 FROM ANALISE_COMPRAS_NOVA 
WHERE ANALISE_COMPRAS_NOVA.CODPROD = UP.CODPROD 
  AND ANALISE_COMPRAS_NOVA.CONTROLE = UP.CONTROLE 
  AND ANALISE_COMPRAS_NOVA.PK_CODEMP = UP.PK_CODEMP);

UPDATE ANALISE_COMPRAS_NOVA UP 
   SET ESTEXC =
(SELECT TRUNC(CASE WHEN ESTATUAL > ESTMAX THEN ESTATUAL - ESTMAX ELSE 0 END) AS ESTEXC 
 FROM ANALISE_COMPRAS_NOVA 
WHERE ANALISE_COMPRAS_NOVA.CODPROD = UP.CODPROD 
  AND ANALISE_COMPRAS_NOVA.CONTROLE = UP.CONTROLE 
  AND ANALISE_COMPRAS_NOVA.PK_CODEMP = UP.PK_CODEMP);

UPDATE ANALISE_COMPRAS_NOVA UP 
   SET ESTEXCTOT =
(SELECT SUM(TRUNC(CASE WHEN ESTATUAL > ESTMAX THEN ESTATUAL - ESTMAX ELSE 0 END)) AS ESTEXCTOT
   FROM ANALISE_COMPRAS_NOVA 
  WHERE ANALISE_COMPRAS_NOVA.CODPROD = UP.CODPROD 
    AND ANALISE_COMPRAS_NOVA.CONTROLE = UP.CONTROLE);

