CREATE OR REPLACE TRIGGER TRG_INC_UPD_TGFPAR_REGRA
/* ----------------------------------------------------------------------------
-- AUTOR: LEANDRO MARCOS MOREIRA 
-- OBJETO: TRIGGER PERSONALIZADA 
-- OBJETIVO DO PROJETO: INSERIR TABELA DE PRECO PARA CLIENTES NOVOS 
*/ ---------------------------------------------------------------------------
BEFORE INSERT OR UPDATE ON SANKHYA.TGFPAR REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
WHEN (
NEW.CODTAB IS NULL OR
NEW.CLIENTE <> OLD.CLIENTE OR
NEW.FORNECEDOR <> OLD.FORNECEDOR
      )
DECLARE
    P_UF TSICID.UF%TYPE;
BEGIN 
   -- SE  ESTIVER DUPLICANDO OU INCLUINDO UM PARCEIRO ELE COLOCAR CODIGO 4 NA TABELADE PRECO PARA ESSE PARCEIRO
    IF (:NEW.CODTAB IS NULL) THEN
        :NEW.CODTAB := 4;
    END IF;

    -- IMPEDIR CLIENTE = 'S' E FORECEDOR = 'S' NO ESTADO DE 'MG'
    IF (:NEW.CLIENTE = 'S' AND :NEW.FORNECEDOR = 'S' AND :NEW.CODTIPPARC IN (30800, 31300)) THEN
        SELECT CID.UF
          INTO P_UF
          FROM TSICID CID
         WHERE CID.CODCID = :NEW.CODCID;

        -- SE UF = 13 'MG' REALIZA O BLOQUEIO
        IF (P_UF = 13) THEN
            RAISE_APPLICATION_ERROR(-20101 ,'Não é permitido CLIENTE = SIM e FORNECEDOR = SIM para o estado de MG e Tipo de Parceiro = ' || :NEW.CODTIPPARC);
        END IF;
    END IF;
END;
