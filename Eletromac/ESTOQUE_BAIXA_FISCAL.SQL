SELECT
  TO_CHAR(CAB.DTNEG, 'YYYYMM') AS ORDEM ,
  TO_CHAR(CAB.DTNEG, 'MON/YYYY') AS PERIODO ,
  (
  SELECT
    ROUND(SUM(ESTOQUE * Obtem_Custo_semicm(SALDO_ESTOQUE.CODPROD)), 2)
  FROM
    SALDO_ESTOQUE
  WHERE
    CODEMP = 2
    AND CODLOCAL = 4
    AND DTNEG <= :PERIODO.FIN) AS LOC04_EMP2 ,
  /*
  (
  SELECT
    ROUND(SUM(ESTOQUE * Obtem_Custo_semicm(CODPROD)), 2)
  FROM
    SALDO_ESTOQUE
  WHERE
    CODEMP = 2
    AND CODLOCAL = 4
    AND DTNEG <= LAST_DAY(TO_DATE('01' || TO_CHAR(CAB.DTNEG, 'MON/YYYY')))) - (
  SELECT
    ROUND(SUM(ESTOQUE * Obtem_Custo_semicm(CODPROD)), 2)
  FROM
    SALDO_ESTOQUE
  WHERE
    CODEMP = 2
    AND CODLOCAL = 4
    AND DTNEG <= TO_CHAR(ADD_MONTHS(LAST_DAY(TO_DATE('01' || TO_CHAR(CAB.DTNEG, 'MON/YYYY'))), -1), 'DD/MM/YYYY')) AS LOC04_EMP2_VARIACAO ,
    */
  (
  SELECT
    ROUND(SUM(ESTOQUE * Obtem_Custo_semicm(SALDO_ESTOQUE.CODPROD)), 2)
  FROM
    SALDO_ESTOQUE
  WHERE
    CODEMP = 1
    AND CODLOCAL = 9
    AND DTNEG <= :PERIODO.FIN) AS LOC09_EMP1 ,
  (
  SELECT
    ROUND(SUM(ESTOQUE * Obtem_Custo_semicm(SALDO_ESTOQUE.CODPROD)), 2)
  FROM
    SALDO_ESTOQUE
  WHERE
    ((CODEMP = 1
    AND CODLOCAL = 9)
    OR (CODEMP = 2
    AND CODLOCAL = 4))
    AND DTNEG <= :PERIODO.FIN) AS SOMA_LOC4_E_9 ,
SUM(CASE WHEN CAB.CODEMP = 1 AND CAB.CODTIPOPER = 154 AND ITE.CODLOCALORIG = 4 AND ITE.ATUALESTOQUE = 1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS ENTRADA154 ,
  SUM(CASE WHEN CAB.CODEMP = 2 AND CAB.CODTIPOPER = 154 AND ITE.CODLOCALORIG = 4 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS SAIDA154 ,
  SUM(CASE WHEN CAB.CODEMP = 1 AND CAB.CODTIPOPER = 154 AND ITE.CODLOCALORIG = 4 AND ITE.ATUALESTOQUE = 1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) - SUM(CASE WHEN CAB.CODEMP = 2 AND CAB.CODTIPOPER = 154 AND ITE.CODLOCALORIG = 4 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG ELSE 0 END) AS VARIACAO154 ,
  SUM(CASE WHEN CAB.CODTIPOPER = 332 AND ITE.CODLOCALORIG IN (1,3) AND ITE.ATUALESTOQUE = 1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS ENTRADA332 ,
  SUM(CASE WHEN CAB.CODTIPOPER = 141 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS SAIDA141 ,
  SUM(CASE WHEN CAB.CODTIPOPER = 141 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) - SUM(CASE WHEN CAB.CODTIPOPER = 332 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = 1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS VARIACAO332_141,
  SUM(CASE WHEN CAB.CODTIPOPER = 133 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = 1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS ENTRADA133 ,
  SUM(CASE WHEN CAB.CODTIPOPER = 133 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS SAIDA133 ,
  SUM(CASE WHEN CAB.CODTIPOPER = 133 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = 1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) -  SUM(CASE WHEN CAB.CODTIPOPER = 133 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS VARIACAO133 ,
  SUM(CASE WHEN CAB.CODTIPOPER = 147 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS SAIDA147,
  SUM(CASE WHEN CAB.CODTIPOPER = 133 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = 1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) - SUM(CASE WHEN CAB.CODTIPOPER = 133 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG ELSE 0 END) - SUM(CASE WHEN CAB.CODTIPOPER = 147 AND ITE.CODLOCALORIG = 9 AND ITE.ATUALESTOQUE = -1 THEN ITE.QTDNEG * Obtem_Custo_semicm2(ITE.CODPROD, CAB.DTNEG) ELSE 0 END) AS VAR133_147
FROM
  TGFCAB CAB ,
  TGFITE ITE
WHERE
  ITE.NUNOTA = CAB.NUNOTA
  AND CAB.STATUSNOTA = 'L'
  AND ITE.USOPROD <> 'D'
  AND ITE.ATUALESTOQUE <> 0
  AND CAB.DTNEG BETWEEN :PERIODO.INI AND :PERIODO.FIN
   AND CAB.CODEMP IN :EMPRESA
GROUP BY
  TO_CHAR(CAB.DTNEG, 'YYYYMM') ,
  TO_CHAR(CAB.DTNEG, 'MON/YYYY')
ORDER BY
  ORDEM ASC