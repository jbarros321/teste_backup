CREATE OR REPLACE TRIGGER TRG_INS_UPD_TGFCAB_REGRA
BEFORE INSERT OR UPDATE
ON SANKHYA.TGFCAB REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
WHEN (
    (NEW.CODTIPOPER IN (2,113, 125,127,133,155,18,134,154,622,206,612) AND NEW.STATUSNOTA = 'L') 
 OR (NEW.TIPMOV = 'C' AND NEW.STATUSNOTA <> OLD.STATUSNOTA)
 OR (NEW.TIPMOV = 'O' AND NEW.STATUSNOTA <> OLD.STATUSNOTA)
)
DECLARE P_COUNT INT;
        P_SOMA NUMBER;
        P_VLRSUBST NUMBER;
        P_CODEMP TSIUSU.CODEMP%TYPE;
        P_CODPROD TGFPRO.CODPROD%TYPE;
BEGIN

-- REGRA PARA FATURAMENTO DE PEDIDOS / PROCESSO DE SEPARACAO
  IF :NEW.STATUSNOTA = 'L' THEN
     :NEW.AD_TEMPOCONF := SYSDATE-1/24/60;
  END IF;

-- REGRAS PARA TRANSFERÊNCIAS INTERNAS TOP 18 E TOP 134
  IF :NEW.CODTIPOPER IN (18,134) THEN
       IF NOT ((:NEW.CODEMP = 1 AND :NEW.CODEMPNEGOC = 1)
           OR (:NEW.CODEMP = 31 AND :NEW.CODEMPNEGOC = 31)
           OR (:NEW.CODEMP = 41 AND :NEW.CODEMPNEGOC = 41)
           OR (:NEW.CODEMP = 51 AND :NEW.CODEMPNEGOC = 51))THEN
         RAISE_APPLICATION_ERROR(-20101 ,'Não é permitido utilizar TOP ' || :NEW.CODTIPOPER || ' entre empresas distintas.');
       END IF;
  END IF;

-- REGRAS PARA TRANSFERÊNCIAS INTERNAS TOP 154
  IF :NEW.CODTIPOPER = 154 THEN
       IF  NOT ((:NEW.CODEMP = 1 AND :NEW.CODEMPNEGOC = 2)
            OR (:NEW.CODEMP = 2 AND :NEW.CODEMPNEGOC = 1)
            OR (:NEW.CODEMP = 31 AND :NEW.CODEMPNEGOC = 32)
            OR (:NEW.CODEMP = 32 AND :NEW.CODEMPNEGOC = 31)
            OR (:NEW.CODEMP = 41 AND :NEW.CODEMPNEGOC = 42)
            OR (:NEW.CODEMP = 42 AND :NEW.CODEMPNEGOC = 41)
            OR (:NEW.CODEMP = 51 AND :NEW.CODEMPNEGOC = 52)
            OR (:NEW.CODEMP = 41 AND :NEW.CODEMPNEGOC = 41)
            OR (:NEW.CODEMP = 2 AND :NEW.CODEMPNEGOC = 2)
            OR (:NEW.CODEMP = 52 AND :NEW.CODEMPNEGOC = 51)) THEN
          RAISE_APPLICATION_ERROR(-20101 ,'Não é permitido utilizar TOP 154 (Transferência Local 4) entre empresas: ' || :NEW.CODEMP || ' e ' || :NEW.CODEMPNEGOC || '.');
        END IF;
  END IF;

-- REGRAS PARA TRANSFERÊNCIA ELETRÔNICA TOP 622
  IF :NEW.CODTIPOPER = 622 THEN 
       IF NOT ((:NEW.CODEMP = 1 AND :NEW.CODEMPNEGOC = 31)
           OR (:NEW.CODEMP = 1 AND :NEW.CODEMPNEGOC = 41)   
           OR (:NEW.CODEMP = 1 AND :NEW.CODEMPNEGOC = 51)
           OR (:NEW.CODEMP = 31 AND :NEW.CODEMPNEGOC = 1)
           OR (:NEW.CODEMP = 31 AND :NEW.CODEMPNEGOC = 41)
           OR (:NEW.CODEMP = 31 AND :NEW.CODEMPNEGOC = 51)
           OR (:NEW.CODEMP = 41 AND :NEW.CODEMPNEGOC = 1)
           OR (:NEW.CODEMP = 41 AND :NEW.CODEMPNEGOC = 31)
           OR (:NEW.CODEMP = 41 AND :NEW.CODEMPNEGOC = 51)
           OR (:NEW.CODEMP = 51 AND :NEW.CODEMPNEGOC = 1)
           OR (:NEW.CODEMP = 51 AND :NEW.CODEMPNEGOC = 31)
           OR (:NEW.CODEMP = 51 AND :NEW.CODEMPNEGOC = 41)) THEN
         RAISE_APPLICATION_ERROR(-20101 ,'Não é permitido utilizar TOP 622 (Transferência NF-E) entre empresas: ' || :NEW.CODEMP || ' e ' || :NEW.CODEMPNEGOC || '.');
       END IF;
  END IF;

 -- REGRA PARA RODRIGO NS CONTABILIDADE
 IF UPDATING('STATUSNOTA') THEN
  IF :NEW.CODTIPOPER IN (206, 612) AND :NEW.STATUSNOTA = 'L' THEN
       IF (:NEW.VLRICMSDIFALDEST > 0 OR :NEW.VLRSUBST > 0) AND Stp_Get_Codusulogado NOT IN (0, 31, 46, 32, 103, 61, 150) THEN
         RAISE_APPLICATION_ERROR(-20101 ,'Recolher Guia de ICMS/ST Usuários Permitidos: (Edinaldo, Junior, Marcelo, Fernanda, Delfino, Luciele)');
     END IF;
  END IF;
END IF;

  IF :NEW.CODTIPOPER = 155 AND :NEW.SERIENOTA = 'PV' THEN
    :NEW.SERIENOTA := NULL;
  END IF;

  -- REGRA PARA LANÇAMENTO DE ENTRADA DE ESTOQUE
  IF :NEW.CODTIPOPER IN (113) AND :NEW.STATUSNOTA = 'L' THEN
     SELECT CODEMP
       INTO P_CODEMP 
       FROM TSIUSU
      WHERE CODUSU = Stp_Get_Codusulogado;
      IF :NEW.CODEMP <> P_CODEMP AND Stp_Get_Codusulogado NOT IN (46, 32, 134, 133, 131,150) THEN 
         RAISE_APPLICATION_ERROR(-20101 ,'Proibido lançamento para empresa distinta do usuário, exceção: (Junior, Marcelo, Luciano, Eder, Alessandro, Luciele)');
      END IF;
  END IF;

  IF (:NEW.TIPMOV = 'C' AND :NEW.STATUSNOTA <> :OLD.STATUSNOTA AND :NEW.CODTIPOPER NOT IN (129)) THEN
      IF (TRUNC(:NEW.DTENTSAI) <> TRUNC(SYSDATE)) THEN
            RAISE_APPLICATION_ERROR(-20101 ,'A data de entrada e saida está diferente da data atual! Ajustar!');
      END IF;
  END IF;

-- REGRA PARA PEDIDOS DE COMPRA, QUANDO UTILIZADO A TAB 04 COMO VALOR IMPEDIR O PEDIDO DE COMPRA
  IF (:NEW.TIPMOV = 'O' AND :NEW.STATUSNOTA <> :OLD.STATUSNOTA) THEN
    FOR ITE IN (SELECT CODPROD
                     , SEQUENCIA
                    FROM TGFITE I
                    WHERE I.NUNOTA = :NEW.NUNOTA)
        LOOP
          BEGIN
            SELECT EXC.CODPROD
              INTO P_CODPROD   
              FROM TGFEXC EXC
             WHERE EXC.NUTAB = 919
               AND EXC.TIPO = 'V'
               AND EXC.CODPROD = ITE.CODPROD;
               EXCEPTION WHEN NO_DATA_FOUND THEN
               P_CODPROD := NULL;
          END;

            IF (P_CODPROD IS NOT NULL) THEN
              RAISE_APPLICATION_ERROR(-20101, 'NÃO É POSSÍVEL CONFIRMAR PEDIDO DE COMPRA ' || :NEW.NUMNOTA || ' MOTIVO: PRODUTO ' || ITE.CODPROD || ' ESTÁ NA TAB 04 COMO VALOR! ');
            END IF;
        END LOOP; 

  END IF;

END;
