CREATE OR REPLACE TRIGGER TRG_UPD_TGFITE_REGRA
/* ----------------------------------------
-- TRIGGER PERSONALIZADA
-- OBJETO: TRIGGER
-- OBJETIVO: IMPEDIR LANÇAMENTOS ERRADOS
-- AUTOR: LEANDRO MARCOS MOREIRA
*/ ---------------------------------------
BEFORE UPDATE ON SANKHYA.TGFITE 
FOR EACH ROW
DECLARE 
    P_CODTIPOPER   NUMBER (18);
    P_TIPCONTEST VARCHAR2(15);
    P_TIPMOV VARCHAR2(15);
    P_CODPROD NUMBER(20);
BEGIN 
    BEGIN 
        SELECT CAB.CODTIPOPER INTO P_CODTIPOPER 
        FROM TGFCAB CAB 
        WHERE CAB.CODTIPOPER NOT IN (1,50)
        AND CAB.NUNOTA = :NEW.NUNOTA; 
            EXCEPTION WHEN NO_DATA_FOUND THEN 
        RETURN;
        
        SELECT TIPCONTEST INTO P_TIPCONTEST FROM TGFPRO
        WHERE CODPROD = :NEW.CODPROD;  
    END; 
    
    IF :NEW.CODEMP <> 41 AND ((:NEW.VLRDESC < 0) OR (:NEW.SEQUENCIA < 0) OR (:NEW.QTDENTREGUE > :NEW.QTDNEG)) THEN
        IF (P_CODTIPOPER not in (1,50)) AND :NEW.SEQUENCIA > 0 AND Stp_Get_Codusulogado NOT IN (0,25) THEN 
            RAISE_APPLICATION_ERROR(-20101, 'NÃO É PERMITIDO DESCONTO NEGATIVO'); 
        END IF;
        IF (P_CODTIPOPER = 134) AND :NEW.SEQUENCIA < 0 AND :NEW.CODLOCALORIG NOT IN (1, 3, 8) THEN
            RAISE_APPLICATION_ERROR(-20101, 'LOCAL DE DESTINO ' || :NEW.CODLOCALORIG || ' BLOQUEADO');
        END IF;
        IF :NEW.QTDENTREGUE > :NEW.QTDNEG THEN
            :NEW.QTDENTREGUE := :NEW.QTDNEG;
        END IF;
     END IF;
END;
