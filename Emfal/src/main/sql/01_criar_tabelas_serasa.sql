-- Tabela de configuracao da integracao Serasa
CREATE TABLE AD_SERASACONFIG (
    CODCONFIG NUMBER(10) NOT NULL,
    CHAVE VARCHAR2(100) NOT NULL,
    VALOR VARCHAR2(500),
    DESCRICAO VARCHAR2(200),
    ATIVO CHAR(1) DEFAULT 'S',
    DTALTERACAO DATE DEFAULT SYSDATE,
    USUARIOALTERACAO VARCHAR2(50),
    CONSTRAINT PK_AD_SERASACONFIG PRIMARY KEY (CODCONFIG),
    CONSTRAINT UK_AD_SERASACONFIG_CHAVE UNIQUE (CHAVE)
);

-- Comentarios da tabela AD_SERASACONFIG
COMMENT ON TABLE AD_SERASACONFIG IS 'Configuracoes da integracao Serasa Experian';
COMMENT ON COLUMN AD_SERASACONFIG.CODCONFIG IS 'Codigo unico da configuracao';
COMMENT ON COLUMN AD_SERASACONFIG.CHAVE IS 'Chave da configuracao';
COMMENT ON COLUMN AD_SERASACONFIG.VALOR IS 'Valor da configuracao';
COMMENT ON COLUMN AD_SERASACONFIG.DESCRICAO IS 'Descricao da configuracao';
COMMENT ON COLUMN AD_SERASACONFIG.ATIVO IS 'Indica se a configuracao esta ativa (S/N)';
COMMENT ON COLUMN AD_SERASACONFIG.DTALTERACAO IS 'Data da ultima alteracao';
COMMENT ON COLUMN AD_SERASACONFIG.USUARIOALTERACAO IS 'Usuario que fez a ultima alteracao';

-- Tabela de logs da integracao Serasa
CREATE TABLE AD_SERASALOG (
    CODLOG NUMBER(10) NOT NULL,
    TIPOOPERACAO VARCHAR2(50) NOT NULL,
    DOCUMENTO VARCHAR2(20),
    STATUS VARCHAR2(20) NOT NULL,
    MENSAGEM VARCHAR2(1000),
    DADOSEXTRAS CLOB,
    DTCRIACAO DATE DEFAULT SYSDATE,
    USUARIO VARCHAR2(50),
    CONSTRAINT PK_AD_SERASALOG PRIMARY KEY (CODLOG)
);

-- Comentarios da tabela AD_SERASALOG
COMMENT ON TABLE AD_SERASALOG IS 'Logs de operacoes da integracao Serasa';
COMMENT ON COLUMN AD_SERASALOG.CODLOG IS 'Codigo unico do log';
COMMENT ON COLUMN AD_SERASALOG.TIPOOPERACAO IS 'Tipo da operacao realizada';
COMMENT ON COLUMN AD_SERASALOG.DOCUMENTO IS 'Documento consultado (CPF/CNPJ)';
COMMENT ON COLUMN AD_SERASALOG.STATUS IS 'Status da operacao';
COMMENT ON COLUMN AD_SERASALOG.MENSAGEM IS 'Mensagem descritiva';
COMMENT ON COLUMN AD_SERASALOG.DADOSEXTRAS IS 'Dados extras em formato JSON';
COMMENT ON COLUMN AD_SERASALOG.DTCRIACAO IS 'Data de criacao do log';
COMMENT ON COLUMN AD_SERASALOG.USUARIO IS 'Usuario que executou a operacao';

-- Tabela de monitoramento continuo
CREATE TABLE AD_SERASAMONITOR (
    CODMONITOR NUMBER(10) NOT NULL,
    DOCUMENTO VARCHAR2(20) NOT NULL,
    TIPOOPERACAO VARCHAR2(50) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    DADOSMONITOR CLOB,
    DTPROXIMAMONITOR DATE,
    ATIVO CHAR(1) DEFAULT 'S',
    DTCRIACAO DATE DEFAULT SYSDATE,
    DTALTERACAO DATE,
    CONSTRAINT PK_AD_SERASAMONITOR PRIMARY KEY (CODMONITOR)
);

-- Comentarios da tabela AD_SERASAMONITOR
COMMENT ON TABLE AD_SERASAMONITOR IS 'Monitoramento continuo de documentos';
COMMENT ON COLUMN AD_SERASAMONITOR.CODMONITOR IS 'Codigo unico do monitoramento';
COMMENT ON COLUMN AD_SERASAMONITOR.DOCUMENTO IS 'Documento monitorado';
COMMENT ON COLUMN AD_SERASAMONITOR.TIPOOPERACAO IS 'Tipo da operacao monitorada';
COMMENT ON COLUMN AD_SERASAMONITOR.STATUS IS 'Status do monitoramento';
COMMENT ON COLUMN AD_SERASAMONITOR.DADOSMONITOR IS 'Dados do monitoramento em JSON';
COMMENT ON COLUMN AD_SERASAMONITOR.DTPROXIMAMONITOR IS 'Data da proxima verificacao';
COMMENT ON COLUMN AD_SERASAMONITOR.ATIVO IS 'Indica se o monitoramento esta ativo';
COMMENT ON COLUMN AD_SERASAMONITOR.DTCRIACAO IS 'Data de criacao';
COMMENT ON COLUMN AD_SERASAMONITOR.DTALTERACAO IS 'Data da ultima alteracao';

-- Tabela de alertas automaticos
CREATE TABLE AD_SERASAALERTAS (
    CODALERTA NUMBER(10) NOT NULL,
    DOCUMENTO VARCHAR2(20) NOT NULL,
    TIPOALERTA VARCHAR2(50) NOT NULL,
