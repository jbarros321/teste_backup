COMMENT ON COLUMN AD_SERASARESULTADOS.CODRESULTADO IS 'Codigo unico do resultado';
COMMENT ON COLUMN AD_SERASARESULTADOS.CODPARC IS 'Codigo do parceiro';
COMMENT ON COLUMN AD_SERASARESULTADOS.DOCUMENTO IS 'Documento consultado';
COMMENT ON COLUMN AD_SERASARESULTADOS.TIPOCONSULTA IS 'Tipo da consulta (PF/PJ)';
COMMENT ON COLUMN AD_SERASARESULTADOS.SCOREFINAL IS 'Score final calculado';
COMMENT ON COLUMN AD_SERASARESULTADOS.RECOMENDACAO IS 'Recomendacao final';
COMMENT ON COLUMN AD_SERASARESULTADOS.DADOSCOMPLETOS IS 'Dados completos em JSON';
