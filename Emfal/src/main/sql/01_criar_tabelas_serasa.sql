COMMENT ON COLUMN AD_SERASAALERTAS.DOCUMENTO IS 'Documento para monitoramento';
COMMENT ON COLUMN AD_SERASAALERTAS.TIPOALERTA IS 'Tipo do alerta';
COMMENT ON COLUMN AD_SERASAALERTAS.PARAMETROS IS 'Parametros do alerta em JSON';
COMMENT ON COLUMN AD_SERASAALERTAS.ATIVO IS 'Indica se o alerta esta ativo';
COMMENT ON COLUMN AD_SERASAALERTAS.DTPROXIMAEXECUCAO IS 'Data da proxima execucao';
COMMENT ON COLUMN AD_SERASAALERTAS.DTCRIACAO IS 'Data de criacao';
COMMENT ON COLUMN AD_SERASAALERTAS.DTALTERACAO IS 'Data da ultima alteracao';

-- Tabela de resultados das consultas
CREATE TABLE AD_SERASARESULTADOS (
    CODRESULTADO NUMBER(10) NOT NULL,
    CODPARC NUMBER(10),
    DOCUMENTO VARCHAR2(20) NOT NULL,
    TIPOCONSULTA VARCHAR2(10) NOT NULL,
