package br.com.petkids.neogrid.model.dto;

public class ClienteDTO {
    private String codigoCliente;
    private String cgcCpf;
    private String tipoPessoa;
    private String cep;
    private String uf;
    private String cidade;
    private String endereco;
    private String bairro;
    private String nomeCliente;
    private String codigoSegmento;
    private String frequenciaVisita;
    private String telefone;
    private String contato;

    public String getCodigoCliente() { return codigoCliente; }
    public void setCodigoCliente(String codigoCliente) { this.codigoCliente = codigoCliente; }
    public String getCgcCpf() { return cgcCpf; }
    public void setCgcCpf(String cgcCpf) { this.cgcCpf = cgcCpf; }
    public String getTipoPessoa() { return tipoPessoa; }
    public void setTipoPessoa(String tipoPessoa) { this.tipoPessoa = tipoPessoa; }
    public String getCep() { return cep; }
    public void setCep(String cep) { this.cep = cep; }
    public String getUf() { return uf; }
    public void setUf(String uf) { this.uf = uf; }
    public String getCidade() { return cidade; }
    public void setCidade(String cidade) { this.cidade = cidade; }
    public String getEndereco() { return endereco; }
    public void setEndereco(String endereco) { this.endereco = endereco; }
    public String getBairro() { return bairro; }
    public void setBairro(String bairro) { this.bairro = bairro; }
    public String getNomeCliente() { return nomeCliente; }
    public void setNomeCliente(String nomeCliente) { this.nomeCliente = nomeCliente; }
    public String getCodigoSegmento() { return codigoSegmento; }
    public void setCodigoSegmento(String codigoSegmento) { this.codigoSegmento = codigoSegmento; }
    public String getFrequenciaVisita() { return frequenciaVisita; }
    public void setFrequenciaVisita(String frequenciaVisita) { this.frequenciaVisita = frequenciaVisita; }
    public String getTelefone() { return telefone; }
    public void setTelefone(String telefone) { this.telefone = telefone; }
    public String getContato() { return contato; }
    public void setContato(String contato) { this.contato = contato; }
}
